using System.Collections;
using UnityEngine;
using UnityEngine.InputSystem;

/// <summary>
/// The ONLY object you need in the scene. On Play it builds the run: upgrade system, human, ghost, camera,
/// background, spawner, HUD and upgrade picker. Every visual object can come from a prefab (assign them below, or
/// use the "Human & Ghost" editor menu to generate and assign them). Empty slots fall back to code-built objects.
/// </summary>
public class GameManager : MonoBehaviour
{
    public static GameManager Instance { get; private set; }

    [Header("Balance (all editable in the Inspector)")]
    public GameTuning tuning = new GameTuning();

    [Header("Prefabs (generated by the 'Human & Ghost' menu; leave empty to use code-built placeholders)")]
    public GameObject humanPrefab;
    public GameObject ghostPrefab;
    public GameObject enemyPrefab;
    [Tooltip("Shared by human bullets, ghost shots and charged shots (color/size set by code).")]
    public GameObject projectilePrefab;
    public GameObject xpOrbPrefab;
    public GameObject fxRingPrefab;
    public GameObject backgroundPrefab;
    public GameObject hudPrefab;
    public GameObject upgradeSelectionPrefab;
    [Tooltip("Human height relative to the ghost. 1 = same height.")]
    public float humanSizeRelativeToGhost = 1f;

    [Header("Optional")]
    [Tooltip("Leave empty to use Camera.main (or one is created).")]
    public Camera gameCamera;
    public bool confineCursorToWindow = true;
    const string BestTimeKey = "BestTime";
    public float BestTime { get; private set; }

    // ---------------- Run state ----------------
    public Human HumanPlayer { get; private set; }
    public Ghost GhostPlayer { get; private set; }
    public UpgradeSystem Upgrades { get; private set; }
    public float ElapsedTime { get; private set; }
    public float Xp { get; private set; }
    public int LevelsGained { get; private set; }
    public bool Paused { get; private set; }
    public bool GameOver { get; private set; }
    /// <summary>True while paused, dead, or for one frame after the picker closes (so the confirming click/Space isn't read as an ability).</summary>
    public bool InputLocked => Paused || GameOver || Time.frameCount <= lockUntilFrame;
    public float CurrentThreshold => tuning.xpThreshold + tuning.xpThresholdGrowthPerLevel * LevelsGained;
    public float XpProgress => Mathf.Clamp01(Xp / Mathf.Max(1f, CurrentThreshold));

    GameObject runRoot;
    UpgradeSelectionUI selectionUI;
    bool restarting;
    int runId;
    int lockUntilFrame = -1;

    void Awake()
    {
        if (Instance != null && Instance != this) { Destroy(gameObject); return; }
        Instance = this;
        if (confineCursorToWindow) Cursor.lockState = CursorLockMode.Confined;
        BestTime = PlayerPrefs.GetFloat(BestTimeKey, 0f);
        Build();
    }

    void OnDestroy() { if (Instance == this) Instance = null; }

    /// <summary>Instantiates a prefab (or an empty GameObject if prefab is null) under the current run.</summary>
    public static GameObject Create(GameObject prefab, string name)
    {
        Transform parent = (Instance != null && Instance.runRoot != null) ? Instance.runRoot.transform : null;
        GameObject go;
        if (prefab != null) go = Instantiate(prefab, parent, false);
        else
        {
            go = new GameObject(name);
            if (parent != null) go.transform.SetParent(parent, false);
        }
        go.name = name;
        return go;
    }

    // ---------------- Build / restart ----------------
    void Build()
    {
        runId++;
        Time.timeScale = 1f;
        Paused = false;
        GameOver = false;
        ElapsedTime = 0f;
        Xp = 0f;
        LevelsGained = 0;
        Enemy.All.Clear();
        XpOrb.All.Clear();

        runRoot = new GameObject("Run");

        var upGo = new GameObject("Upgrades");
        upGo.transform.SetParent(runRoot.transform, false);
        Upgrades = upGo.AddComponent<UpgradeSystem>();

        var hGo = Create(humanPrefab, "Human");
        hGo.transform.position = Vector3.zero;
        HumanPlayer = hGo.GetOrAdd<Human>();

        var gGo = Create(ghostPrefab, "Ghost");
        gGo.transform.position = new Vector3(2f, 1f, 0f);
        GhostPlayer = gGo.GetOrAdd<Ghost>();
        MatchHeight(hGo, gGo, humanSizeRelativeToGhost);

        var cam = SetupCamera();
        cam.Init(HumanPlayer.transform, GhostPlayer.transform);

        var bgGo = Create(backgroundPrefab, "Background");
        bgGo.GetOrAdd<ScrollingBackground>().Init(cam);

        var spGo = new GameObject("EnemySpawner");
        spGo.transform.SetParent(runRoot.transform, false);
        spGo.AddComponent<EnemySpawner>();

        Create(hudPrefab, "HUD").GetOrAdd<HUD>();
        selectionUI = Create(upgradeSelectionPrefab, "UpgradeSelection").GetOrAdd<UpgradeSelectionUI>();
    }
    static void MatchHeight(GameObject target, GameObject reference, float multiplier)
    {
        var tsr = target.GetComponent<SpriteRenderer>();
        var rsr = reference.GetComponent<SpriteRenderer>();
        if (tsr == null || rsr == null || tsr.sprite == null) return;

        float want = rsr.bounds.size.y * multiplier;   // ghost's on-screen height
        float have = tsr.sprite.bounds.size.y;          // human sprite's unscaled height
        target.transform.localScale = Vector3.one * (want / have);
    }

    DynamicCamera SetupCamera()
    {
        Camera cam = gameCamera != null ? gameCamera : Camera.main;
        if (cam == null) cam = FindFirstObjectByType<Camera>();
        if (cam == null)
        {
            var go = new GameObject("Main Camera");
            go.tag = "MainCamera";
            cam = go.AddComponent<Camera>();
        }
        if (cam.GetComponent<AudioListener>() == null) cam.gameObject.AddComponent<AudioListener>();
        cam.orthographic = true;
        cam.clearFlags = CameraClearFlags.SolidColor;
        cam.backgroundColor = new Color(0.07f, 0.08f, 0.11f);
        return cam.gameObject.GetOrAdd<DynamicCamera>();
    }

    public void Restart()
    {
        if (restarting) return;
        StartCoroutine(RestartRoutine());
    }

    IEnumerator RestartRoutine()
    {
        restarting = true;
        runId++;                      // cancels any pending game-over restart
        Time.timeScale = 1f;
        if (runRoot != null) Destroy(runRoot);
        runRoot = null;
        yield return null;            // wait a frame so the old run is fully destroyed
        Build();
        restarting = false;
    }

    // ---------------- Per-frame ----------------
    void Update()
    {
        var kb = Keyboard.current;
        if (kb != null && kb.rKey.wasPressedThisFrame) Restart();
        if (!InputLocked && !restarting) ElapsedTime += Time.deltaTime;
    }

    // ---------------- Experience & upgrades ----------------
    public void AddXp(float amount)
    {
        if (GameOver || restarting) return;
        Xp += amount;
        TryOpenSelection();
    }

    void TryOpenSelection()
    {
        if (Paused || GameOver || Xp < CurrentThreshold || Upgrades == null || selectionUI == null) return;
        Paused = true;
        Time.timeScale = 0f;
        Sfx.Play(SfxId.LevelUp, 1f, 0f);
        selectionUI.Open(Upgrades.DrawOptions(), OnUpgradeChosen);
    }

    void OnUpgradeChosen(UpgradeType chosen)
    {
        Upgrades.Apply(chosen);
        Xp -= CurrentThreshold;
        LevelsGained++;
        Paused = false;
        Time.timeScale = 1f;
        lockUntilFrame = Time.frameCount;
        TryOpenSelection(); // in case enough XP is banked for another pick
    }

    // ---------------- Death ----------------
    public void OnHumanDied()
    {
        if (GameOver) return;
        GameOver = true;

        bool newBest = ElapsedTime > BestTime;
        if (newBest)
        {
            BestTime = ElapsedTime;
            PlayerPrefs.SetFloat(BestTimeKey, BestTime);
            PlayerPrefs.Save();
        }

        Time.timeScale = 0.35f;
        if (HUD.Instance != null) HUD.Instance.ShowGameOver(ElapsedTime, newBest);
        StartCoroutine(GameOverRoutine(runId));
    }

    IEnumerator GameOverRoutine(int id)
    {
        yield return new WaitForSecondsRealtime(tuning.restartDelayAfterDeath);
        if (id == runId) Restart();
    }
}